type WordFloat = [ByteFloat; 4];

fn AddWord(a: WordFloat, b: WordFloat) -> WordFloat {
    // flatten both words to bits
    let mut abits = unsafe { mem::transmute::<WordFloat, [f64; 4 * 8]>(a) };
    let bbits = unsafe { mem::transmute::<WordFloat, [f64; 4 * 8]>(b) };

    for (ai, bi) in abits.iter_mut().zip(bbits) {
        *ai = XOR(*ai, bi);
    }

    unsafe { mem::transmute::<[f64; 4 * 8], WordFloat>(abits) }
}

fn SubWord(word: WordFloat) -> WordFloat {
    let [a, b, c, d] = word;
    [SBOX(a), SBOX(b), SBOX(c), SBOX(d)]
}

fn RotWord(word: WordFloat) -> WordFloat {
    let [a, b, c, d] = word;
    [b, c, d, a]
}

#[rustfmt::skip]
fn Byte2Float(b: u8) -> ByteFloat {
    let mut byte = [0.0; 8];

    if (b & (1 << 0)) == 1 << 0 { byte[7] = 1.0 }
    if (b & (1 << 1)) == 1 << 1 { byte[6] = 1.0 }
    if (b & (1 << 2)) == 1 << 2 { byte[5] = 1.0 }
    if (b & (1 << 3)) == 1 << 3 { byte[4] = 1.0 }
    if (b & (1 << 4)) == 1 << 4 { byte[3] = 1.0 }
    if (b & (1 << 5)) == 1 << 5 { byte[2] = 1.0 }
    if (b & (1 << 6)) == 1 << 6 { byte[1] = 1.0 }
    if (b & (1 << 7)) == 1 << 7 { byte[0] = 1.0 }

    byte
}

fn rcon(mut i: usize) -> WordFloat {
    let mut rc = Byte2Float(1);
    while i > 1 {
        rc = MUL2(rc);
        i -= 1;
    }

    let mut out: WordFloat = unsafe { mem::zeroed() };
    out[0] = rc;

    out
}

fn ExpandKeys(key: StateFloat) -> [StateFloat; 11] {
    const N: usize = 4;

    let K = unsafe { mem::transmute::<StateFloat, [WordFloat; 4]>(key) };
    let mut key_words: [WordFloat; 44] = unsafe { mem::zeroed() };

    for i in 0..key_words.len() {
        let word = if i < 4 {
            K[i]
        } else if i % N == 0 {
            let a = key_words[i - N];
            let b = SubWord(RotWord(key_words[i - 1]));
            let c = rcon(i / N);

            AddWord(AddWord(a, b), c)
        } else {
            let a = key_words[i - N];
            let b = key_words[i - 1];

            AddWord(a, b)
        };

        key_words[i] = word;
    }

    unsafe { mem::transmute::<[WordFloat; 44], [StateFloat; 11]>(key_words) }
}

