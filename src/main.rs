#[allow(clippy::needless_range_loop)]
fn AES(p: StateFloat, k: StateFloat) -> StateFloat {
    let round_keys = ExpandKeys(k);

    let mut x = AddRoundKey(p, round_keys[0]);

    for i in 1..=9 {
        x = SubBytes(x);
        x = ShiftRows(x);
        x = MixColumns(x);
        x = AddRoundKey(x, round_keys[i]);
    }

    x = SubBytes(x);
    x = ShiftRows(x);
    x = AddRoundKey(x, round_keys[10]);
    x
}

