type Column = [ByteFloat; 4];

#[rustfmt::skip]
fn MixColumn(x: Column) -> Column {
    let [a0, b0, c0, d0] = x;

    let a1 = XOR8(MUL2(a0), c0, d0, MUL3(b0));
    let b1 = XOR8(MUL2(b0), a0, d0, MUL3(c0));
    let c1 = XOR8(MUL2(c0), a0, b0, MUL3(d0));
    let d1 = XOR8(MUL2(d0), b0, c0, MUL3(a0));

    [a1, b1, c1, d1]
}

