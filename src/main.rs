// index 0 of ByteFloat is the MSB of the byte
type ByteFloat = [f64; 8];

fn XOR8(a: ByteFloat, b: ByteFloat, c: ByteFloat, d: ByteFloat) -> ByteFloat {
    let mut out = a;

    for (((o, bb), cc), dd) in out.iter_mut().zip(b).zip(c).zip(d) {
        *o = XOR(*o, bb);
        *o = XOR(*o, cc);
        *o = XOR(*o, dd);
    }

    out
}

type StateFloat = [f64; 128];

fn bytes2state(bytes: [u8; 16]) -> StateFloat {
    unsafe { mem::transmute::<[ByteFloat; 16], StateFloat>(bytes.map(Byte2Float)) }
}

fn AddRoundKey(p: StateFloat, k: StateFloat) -> StateFloat {
    let mut out = p;

    for (o, kk) in out.iter_mut().zip(k) {
        *o = XOR(*o, kk);
    }

    out
}

